// Generates src/lib/checks/schema-org-types.ts: every schema.org type that is
// an Organization or an Article (including all subtypes), so the JSON-LD checks
// can recognise e.g. "BankOrCreditUnion" as an Organization.
//
// Usage:
//   curl -sL https://schema.org/version/latest/schemaorg-current-https.jsonld -o schemaorg.jsonld
//   node scripts/gen-schema-org-types.mjs schemaorg.jsonld V30.1   (release from schema.org/docs/releases.html)

import { readFileSync, writeFileSync } from "node:fs";

const input = process.argv[2];
if (!input) {
  console.error("usage: node scripts/gen-schema-org-types.mjs <schemaorg-current-https.jsonld> [release]");
  process.exit(1);
}

const vocab = JSON.parse(readFileSync(input, "utf8"));
const graph = vocab["@graph"];
// The file does not record its own release, so it is passed on the command line.
const version = process.argv[3] ?? "(latest)";

const PREFIX = "schema:";
const asList = (v) => (v == null ? [] : Array.isArray(v) ? v : [v]);

// child type -> parent types
const parents = new Map();
for (const node of graph) {
  if (!asList(node["@type"]).includes("rdfs:Class")) continue;
  const id = node["@id"];
  if (!id?.startsWith(PREFIX)) continue;
  const supers = asList(node["rdfs:subClassOf"])
    .map((s) => s["@id"])
    .filter((s) => s?.startsWith(PREFIX));
  parents.set(id, supers);
}

function descendsFrom(id, root, seen = new Set()) {
  if (id === root) return true;
  if (seen.has(id)) return false;
  seen.add(id);
  return (parents.get(id) ?? []).some((p) => descendsFrom(p, root, seen));
}

function typesUnder(root) {
  return [...parents.keys()]
    .filter((id) => descendsFrom(id, root))
    .map((id) => id.slice(PREFIX.length))
    .sort();
}

const organization = typesUnder("schema:Organization");
const article = typesUnder("schema:Article");

const fmt = (list) => list.map((t) => `  "${t}",`).join("\n");

const out = `// Generated by scripts/gen-schema-org-types.mjs from schema.org ${version}. Don't edit by hand.

/** schema.org Organization and all its subtypes (LocalBusiness, Corporation, BankOrCreditUnion, …). */
export const ORGANIZATION_TYPES: ReadonlySet<string> = new Set([
${fmt(organization)}
]);

/** schema.org Article and all its subtypes (NewsArticle, BlogPosting, TechArticle, …). */
export const ARTICLE_TYPES: ReadonlySet<string> = new Set([
${fmt(article)}
]);
`;

writeFileSync(new URL("../src/lib/checks/schema-org-types.ts", import.meta.url), out);
console.log(`schema.org ${version}: ${organization.length} Organization types, ${article.length} Article types`);
